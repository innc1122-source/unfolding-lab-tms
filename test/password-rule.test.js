// 新密码规则（批次 3 S5；IA B-G13、B-F12、D-25 ①，计划 R-371、G-11）：修改密码与重置密码同一校验 —— 至少 8 位、
// 须同时包含字母和数字、不能与工号相同、不能与原密码相同，每种拒绝带 code；只在设定新密码时校验，已有的弱密码照常登录；
// 系统生成的临时密码至少含 1 个字母和 1 个数字。重置密码一侧的同组 code 见 test/password-reset.test.js。
"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const crypto = require("crypto");
const { DatabaseSync } = require("node:sqlite");
const { ADMIN, startServer, makeClient, loginAs } = require("./helpers.js");

let srv, admin;
test.before(async () => { srv = await startServer(); admin = await loginAs(srv.base, ADMIN); });
test.after(() => srv && srv.stop());

async function newEmployee(employeeId) {
  const r = await admin.post("/api/admin/employees", { name: "Pw " + employeeId, employeeId });
  assert.equal(r.status, 200, JSON.stringify(r.data));
  return { employeeId, password: r.data.password };
}

test("change password: each refusal carries its code (too_short, too_weak, same_as_employee_id, same_as_current, current_password_incorrect)", async () => {
  const e = await newEmployee("PWR-000123");
  const c = await loginAs(srv.base, { employeeId: e.employeeId, password: e.password });
  const tryPw = (currentPassword, newPassword) => c.post("/api/auth/change-password", { currentPassword, newPassword });
  const cases = [
    [e.password, "abc123", "too_short"],
    [e.password, "abcdefghij", "too_weak"],
    [e.password, "1234567890", "too_weak"],
    [e.password, "pwr-000123", "same_as_employee_id"],
    [e.password, e.password, "same_as_current"],
    ["wrong-current-9", "Good-pass-2026", "current_password_incorrect"],
  ];
  for (const [cur, np, code] of cases) {
    const r = await tryPw(cur, np);
    assert.equal(r.status, 400, np);
    assert.equal(r.data.code, code, np);
    assert.match(r.data.error, /[A-Za-z].*[一-鿿]/, "the fallback text carries both languages: " + r.data.error);
  }
  const ok = await tryPw(e.password, "Good-pass-2026");
  assert.equal(ok.status, 200, JSON.stringify(ok.data));
});

test("an existing password that breaks the new rule still signs in — the rule applies only when a new password is set", async () => {
  const e = await newEmployee("PWR-000456");
  // 直接写入一个只含字母的旧密码（与服务端 hashPassword 同一格式：16 字节盐 hex + ":" + scrypt 32 字节 hex）
  const salt = crypto.randomBytes(16).toString("hex");
  const hash = salt + ":" + crypto.scryptSync("lettersonly", salt, 32).toString("hex");
  const db = new DatabaseSync(srv.dbPath);
  try { db.prepare("UPDATE users SET passwordHash = ?, mustChangePassword = 0 WHERE employeeId = ?").run(hash, e.employeeId); } finally { db.close(); }
  const r = await makeClient(srv.base).login({ employeeId: e.employeeId, password: "lettersonly" });
  assert.equal(r.status, 200, JSON.stringify(r.data));
});

test("temporary passwords generated by the system contain at least one letter and one digit", async () => {
  for (let i = 0; i < 25; i++) {
    const e = await newEmployee("PWR-T" + String(i).padStart(4, "0"));
    assert.match(e.password, /[a-z]/i, e.password);
    assert.match(e.password, /[0-9]/, e.password);
    assert.ok(e.password.length >= 8, e.password);
  }
});

test("both password pages state the same rule and check it before sending", () => {
  const fs = require("fs"), path = require("path");
  const read = (f) => fs.readFileSync(path.join(__dirname, "..", "web", "src", "pages", f), "utf8");
  for (const f of ["ChangePassword.jsx", "ResetPassword.jsx"]) {
    const src = read(f);
    assert.match(src, /rule: '至少 8 位，须同时包含字母和数字，不能与工号或原密码相同。'/, f);
    assert.match(src, /rule: 'At least 8 characters, with both letters and digits, and different from your employee ID and your current password\.'/, f);
    assert.match(src, /\/\[A-Za-z\]\/\.test\(/, f + " checks for a letter");
    assert.match(src, /same_as_employee_id/, f + " maps the employee-ID refusal");
    assert.match(src, /same_as_current|sameAsOld/, f + " maps the same-as-current refusal");
  }
});
